const getResponse = (msg: string, mode: Mode): { text: string; escalate?: boolean } => {
  const lower = msg.toLowerCase();

  // Основная база для режима
  const primaryBase = mode === "trainer" ? salesScripts : knowledgeBase;
  for (const item of primaryBase) {
    if (item.keywords.some(kw => lower.includes(kw.toLowerCase()))) {
      return { text: item.answer };
    }
  }

  // В обоих режимах — проверяем вторую базу (скрипты продаж и знания пересекаются)
  const secondaryBase = mode === "trainer" ? knowledgeBase : salesScripts;
  for (const item of secondaryBase) {
    if (item.keywords.some(kw => lower.includes(kw.toLowerCase()))) {
      return { text: item.answer };
    }
  }

  if (lower.includes("привет") || lower.includes("здравст") || lower.includes("добр")) {
    return { text: "Привет! Я ИИ-ассистент НЕТДОЛГОФФ. Знаю всё о банкротстве физических лиц и нашей партнёрской программе. Задайте любой вопрос — отвечу быстро!\n\nДля скриптов продаж переключитесь в режим 🎓 Тренера." };
  }
  if (lower.includes("спасибо") || lower.includes("благодар")) {
    return { text: "Пожалуйста! Если появятся ещё вопросы — всегда готов помочь. Удачных поездок и много клиентов!" };
  }

  if (mode === "trainer") {
    return {
      text: "🎯 Опишите ситуацию подробнее — например:\n• «Как начать диалог?»\n• «Ситуации для разговора»\n• «Пассажир говорит дорого»\n• «Пассажир боится последствий»\n• «Разыграй диалог»\n\nЯ дам готовый скрипт.",
    };
  }

  return {
    text: "По этому вопросу у меня нет точного ответа — лучше уточнить у живого юриста-куратора. Он знает все нюансы и ответит в течение нескольких минут.\n\nПерейдите в раздел «Чат с куратором» 👆",
    escalate: true,
  };
};

